const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);
const lerp = (a, b, t) => a + (b - a) * t;
const smooth = (e0, e1, x) => {
  const t = clamp01((x - e0) / (e1 - e0));
  return t * t * (3 - 2 * t);
};

function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const hex = (h) => [
  parseInt(h.slice(1, 3), 16) / 255,
  parseInt(h.slice(3, 5), 16) / 255,
  parseInt(h.slice(5, 7), 16) / 255,
];

class Surface {
  constructor(w, h, seed) {
    this.w = w;
    this.h = h;
    this.px = new Float32Array(w * h * 4); // rgba, 0..1
    this.rand = mulberry32(seed);
  }

  _mix(x, y, color, w) {
    if (w <= 0 || x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const i = ((y | 0) * this.w + (x | 0)) * 4;
    this.px[i] = lerp(this.px[i], color[0], w);
    this.px[i + 1] = lerp(this.px[i + 1], color[1], w);
    this.px[i + 2] = lerp(this.px[i + 2], color[2], w);
    this.px[i + 3] = Math.max(this.px[i + 3], w);
  }

  fill(r, g, b, a = 1) {
    for (let i = 0; i < this.px.length; i += 4) {
      this.px[i] = r;
      this.px[i + 1] = g;
      this.px[i + 2] = b;
      this.px[i + 3] = a;
    }
  }

  /** Directional light ramp across the frame. */
  ramp(angleDeg, from, to) {
    const a = (angleDeg * Math.PI) / 180;
    const dx = Math.cos(a);
    const dy = Math.sin(a);
    const norm = Math.abs(dx) * this.w + Math.abs(dy) * this.h;
    for (let y = 0; y < this.h; y++) {
      for (let x = 0; x < this.w; x++) {
        const t = clamp01((x * dx + y * dy + (dx < 0 ? this.w : 0) + (dy < 0 ? this.h : 0)) / norm);
        const i = (y * this.w + x) * 4;
        this.px[i] = lerp(from[0], to[0], t);
        this.px[i + 1] = lerp(from[1], to[1], t);
        this.px[i + 2] = lerp(from[2], to[2], t);
        this.px[i + 3] = 1;
      }
    }
  }

  /** Soft elliptical mass — atmosphere, glow, out-of-focus depth. */
  blob(cx, cy, rx, ry, rot, color, alpha = 1, falloff = 2) {
    const c = Math.cos(rot);
    const s = Math.sin(rot);
    const rad = Math.max(rx, ry) * 1.5;
    const x0 = Math.max(0, Math.floor(cx - rad));
    const x1 = Math.min(this.w, Math.ceil(cx + rad));
    const y0 = Math.max(0, Math.floor(cy - rad));
    const y1 = Math.min(this.h, Math.ceil(cy + rad));
    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        const px = x - cx;
        const py = y - cy;
        const u = (px * c + py * s) / rx;
        const v = (-px * s + py * c) / ry;
        const d = u * u + v * v;
        if (d >= 1) continue;
        this._mix(x, y, color, Math.pow(1 - d, falloff) * alpha);
      }
    }
  }

  /** Crisp ellipse — silhouette parts, bokeh discs, sun. */
  disc(cx, cy, rx, ry, rot, color, alpha = 1, feather = 1.5) {
    const c = Math.cos(rot);
    const s = Math.sin(rot);
    const rad = Math.max(rx, ry) + feather + 2;
    const x0 = Math.max(0, Math.floor(cx - rad));
    const x1 = Math.min(this.w, Math.ceil(cx + rad));
    const y0 = Math.max(0, Math.floor(cy - rad));
    const y1 = Math.min(this.h, Math.ceil(cy + rad));
    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        const px = x - cx;
        const py = y - cy;
        const u = (px * c + py * s) / rx;
        const v = (-px * s + py * c) / ry;
        const d = Math.sqrt(u * u + v * v);
        const edge = feather / Math.max(rx, ry);
        this._mix(x, y, color, (1 - smooth(1 - edge, 1, d)) * alpha);
      }
    }
  }

  /** Crisp rotated rectangle — architecture, limbs, hard shadow. */
  quad(cx, cy, w, h, rot, color, alpha = 1, feather = 1.2) {
    const c = Math.cos(rot);
    const s = Math.sin(rot);
    const rad = Math.hypot(w, h) / 2 + feather + 2;
    const x0 = Math.max(0, Math.floor(cx - rad));
    const x1 = Math.min(this.w, Math.ceil(cx + rad));
    const y0 = Math.max(0, Math.floor(cy - rad));
    const y1 = Math.min(this.h, Math.ceil(cy + rad));
    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        const px = x - cx;
        const py = y - cy;
        const u = Math.abs(px * c + py * s) - w / 2;
        const v = Math.abs(-px * s + py * c) - h / 2;
        const a = (1 - smooth(-feather, 0, u)) * (1 - smooth(-feather, 0, v));
        this._mix(x, y, color, a * alpha);
      }
    }
  }

  /** Thick line segment with rounded ends — one bone of a body. */
  capsule(x1, y1, x2, y2, thick, color, alpha = 1) {
    const len = Math.hypot(x2 - x1, y2 - y1);
    this.quad((x1 + x2) / 2, (y1 + y2) / 2, len, thick, Math.atan2(y2 - y1, x2 - x1), color, alpha);
    this.disc(x1, y1, thick / 2, thick / 2, 0, color, alpha, 1.2);
    this.disc(x2, y2, thick / 2, thick / 2, 0, color, alpha, 1.2);
  }

  /**
   * Standing human silhouette assembled from capsules, so every limb stays
   * joined to the body. `u` is full height in px; `pose` (0..1) varies stance.
   */
  figure(cx, footY, u, color, alpha = 1, pose = 0) {
    const lean = (pose - 0.5) * u * 0.07;
    const hipY = footY - u * 0.5;
    const shY = footY - u * 0.83;
    const headY = footY - u * 0.94;
    const hipX = cx + lean * 0.4;
    const shX = cx + lean;

    // Legs, with a little stride so the stance isn't symmetrical.
    const stride = u * (0.02 + pose * 0.07);
    this.capsule(hipX - u * 0.05, hipY, cx - u * 0.055 - stride, footY, u * 0.088, color, alpha);
    this.capsule(hipX + u * 0.05, hipY, cx + u * 0.055 + stride * 0.35, footY, u * 0.088, color, alpha);

    // Torso tapering into shoulders.
    this.capsule(hipX, hipY, shX, shY, u * 0.2, color, alpha);
    this.capsule(shX - u * 0.1, shY + u * 0.012, shX + u * 0.1, shY + u * 0.012, u * 0.075, color, alpha);

    // Arms: upper arm to elbow, forearm hanging from it.
    const elbowY = shY + u * 0.19;
    const lEl = shX - u * (0.13 + Math.sin(pose * 2.1) * 0.05);
    const rEl = shX + u * (0.13 + Math.sin(pose * 3.4) * 0.07);
    this.capsule(shX - u * 0.11, shY + u * 0.012, lEl, elbowY, u * 0.06, color, alpha);
    this.capsule(lEl, elbowY, lEl - u * 0.025, elbowY + u * 0.17, u * 0.05, color, alpha);
    this.capsule(shX + u * 0.11, shY + u * 0.012, rEl, elbowY, u * 0.06, color, alpha);
    this.capsule(rEl, elbowY, rEl + u * 0.035, elbowY + u * 0.17, u * 0.05, color, alpha);

    // Neck and head.
    this.capsule(shX, shY - u * 0.005, shX + lean * 0.2, headY, u * 0.052, color, alpha);
    this.disc(shX + lean * 0.25, headY - u * 0.022, u * 0.05, u * 0.063, lean * 0.3, color, alpha, 1.6);
  }

  rect(x, y, w, h, color, alpha = 1) {
    const x0 = Math.max(0, Math.round(x));
    const y0 = Math.max(0, Math.round(y));
    const x1 = Math.min(this.w, Math.round(x + w));
    const y1 = Math.min(this.h, Math.round(y + h));
    for (let yy = y0; yy < y1; yy++) for (let xx = x0; xx < x1; xx++) this._mix(xx, yy, color, alpha);
  }

  /** Cheap separable box blur — used for depth of field. */
  blur(radius, region) {
    if (radius < 1) return;
    const { x0 = 0, y0 = 0, x1 = this.w, y1 = this.h } = region ?? {};
    const tmp = new Float32Array(this.px.length);
    tmp.set(this.px);
    const r = Math.round(radius);
    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        let a = 0, b = 0, c = 0, n = 0;
        for (let k = -r; k <= r; k++) {
          const sx = x + k;
          if (sx < x0 || sx >= x1) continue;
          const i = (y * this.w + sx) * 4;
          a += tmp[i]; b += tmp[i + 1]; c += tmp[i + 2]; n++;
        }
        const i = (y * this.w + x) * 4;
        this.px[i] = a / n; this.px[i + 1] = b / n; this.px[i + 2] = c / n;
      }
    }
    tmp.set(this.px);
    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        let a = 0, b = 0, c = 0, n = 0;
        for (let k = -r; k <= r; k++) {
          const sy = y + k;
          if (sy < y0 || sy >= y1) continue;
          const i = (sy * this.w + x) * 4;
          a += tmp[i]; b += tmp[i + 1]; c += tmp[i + 2]; n++;
        }
        const i = (y * this.w + x) * 4;
        this.px[i] = a / n; this.px[i + 1] = b / n; this.px[i + 2] = c / n;
      }
    }
  }

  /**
   * Three-stop colour grade: shadows, midtones and highlights each get their
   * own hue, the way a film stock does. Cool shadows into warm mids into a
   * cream highlight is what makes a photograph read as shot rather than
   * rendered — a two-colour duotone never can.
   */
  grade(shadow, mid, highlight, mix = 1) {
    for (let i = 0; i < this.px.length; i += 4) {
      const l = 0.299 * this.px[i] + 0.587 * this.px[i + 1] + 0.114 * this.px[i + 2];
      for (let k = 0; k < 3; k++) {
        const target =
          l < 0.5
            ? lerp(shadow[k], mid[k], l * 2)
            : lerp(mid[k], highlight[k], (l - 0.5) * 2);
        this.px[i + k] = lerp(this.px[i + k], target, mix);
      }
    }
  }

  /**
   * A saturated mass in the frame — the red coat, the car door, the sign.
   * Without one, a graded frame is all one family of hue and reads flat.
   *
   * It *modulates* what is underneath rather than painting over it: the colour
   * is multiplied by the scene's own luminance, so the object picks up the
   * same light and shadow as everything around it. Painting it flat leaves a
   * shape sitting on top of the photograph, which is exactly what it looks
   * like once there is no grain to disguise the join.
   */
  prop(cx, cy, rx, ry, rot, color, alpha = 0.85, round = false) {
    const c = Math.cos(rot);
    const sn = Math.sin(rot);
    const rad = Math.max(rx, ry) * 1.6 + 4;
    const x0 = Math.max(0, Math.floor(cx - rad));
    const x1 = Math.min(this.w, Math.ceil(cx + rad));
    const y0 = Math.max(0, Math.floor(cy - rad));
    const y1 = Math.min(this.h, Math.ceil(cy + rad));
    const feather = 1.5;

    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        const px = x - cx;
        const py = y - cy;
        const u = px * c + py * sn;
        const v = -px * sn + py * c;

        let cover;
        if (round) {
          const d = Math.sqrt((u / rx) * (u / rx) + (v / ry) * (v / ry));
          cover = 1 - smooth(1 - feather / Math.max(rx, ry), 1, d);
        } else {
          cover =
            (1 - smooth(-feather, 0, Math.abs(u) - rx)) *
            (1 - smooth(-feather, 0, Math.abs(v) - ry));
        }
        if (cover <= 0) continue;

        const i = (y * this.w + x) * 4;
        const l = 0.299 * this.px[i] + 0.587 * this.px[i + 1] + 0.114 * this.px[i + 2];
        // Keep a floor under the shading so the object never goes pure black.
        const lit = 0.28 + l * 1.05;
        for (let k = 0; k < 3; k++) {
          this.px[i + k] = lerp(this.px[i + k], clamp01(color[k] * lit), cover * alpha);
        }
      }
    }
  }

  /**
   * Stretch a region to use the full tonal range, taking the black and white
   * points from quantiles so a few stray pixels can't set them.
   *
   * A halftone has only dot size to work with, so an original that sits in the
   * bottom third of the range screens to a flat field of solid ink.
   */
  levels(x, y, w, h, lowQ = 0.02, highQ = 0.98) {
    const lums = [];
    for (let yy = y; yy < y + h; yy += 3) {
      for (let xx = x; xx < x + w; xx += 3) {
        if (xx < 0 || yy < 0 || xx >= this.w || yy >= this.h) continue;
        const i = (yy * this.w + xx) * 4;
        lums.push(0.299 * this.px[i] + 0.587 * this.px[i + 1] + 0.114 * this.px[i + 2]);
      }
    }
    if (!lums.length) return;
    lums.sort((a, b) => a - b);
    const lo = lums[Math.floor(lowQ * (lums.length - 1))];
    const hi = lums[Math.floor(highQ * (lums.length - 1))];
    const span = Math.max(1e-3, hi - lo);

    for (let yy = Math.max(0, y); yy < Math.min(this.h, y + h); yy++) {
      for (let xx = Math.max(0, x); xx < Math.min(this.w, x + w); xx++) {
        const i = (yy * this.w + xx) * 4;
        for (let k = 0; k < 3; k++) this.px[i + k] = clamp01((this.px[i + k] - lo) / span);
      }
    }
  }

  /**
   * Halftone the region: flat ink dots on a flat ground, on a rotated screen.
   * This is the texture in the reference — a photograph reproduced cheaply and
   * enlarged past the point where the screen disappears.
   */
  halftone(x, y, w, h, cell, ink, paper, angleDeg = 22) {
    const src = this.clone();
    this.rect(x, y, w, h, paper, 1);

    const a = (angleDeg * Math.PI) / 180;
    const ca = Math.cos(a);
    const sa = Math.sin(a);
    const cx0 = x + w / 2;
    const cy0 = y + h / 2;
    // Walk the rotated lattice far enough to cover the corners.
    const reach = Math.ceil(Math.hypot(w, h) / cell / 2) + 1;

    for (let j = -reach; j <= reach; j++) {
      for (let i = -reach; i <= reach; i++) {
        const u = i * cell;
        const v = j * cell;
        const px = cx0 + u * ca - v * sa;
        const py = cy0 + u * sa + v * ca;
        if (px < x - cell || px > x + w + cell || py < y - cell || py > y + h + cell) continue;

        const sxi = Math.round(px);
        const syi = Math.round(py);
        if (sxi < 0 || syi < 0 || sxi >= this.w || syi >= this.h) continue;
        const si = (syi * this.w + sxi) * 4;
        const l = 0.299 * src.px[si] + 0.587 * src.px[si + 1] + 0.114 * src.px[si + 2];

        // Dot area tracks ink coverage, so radius follows the square root.
        const r = Math.sqrt(clamp01(1 - l)) * cell * 0.78;
        if (r < 0.35) continue;
        this.disc(px, py, r, r, 0, ink, 1, 0.9);
      }
    }
  }

  contrast(amount, pivot = 0.46) {
    for (let i = 0; i < this.px.length; i += 4) {
      for (let c = 0; c < 3; c++) this.px[i + c] = clamp01(pivot + (this.px[i + c] - pivot) * amount);
    }
  }

  grain(amount) {
    for (let i = 0; i < this.px.length; i += 4) {
      const n = (this.rand() - 0.5) * amount;
      this.px[i] = clamp01(this.px[i] + n);
      this.px[i + 1] = clamp01(this.px[i + 1] + n * 0.92);
      this.px[i + 2] = clamp01(this.px[i + 2] + n * 1.08);
    }
  }

  vignette(strength) {
    const cx = this.w / 2;
    const cy = this.h / 2;
    const max = Math.hypot(cx, cy);
    for (let y = 0; y < this.h; y++) {
      for (let x = 0; x < this.w; x++) {
        const d = Math.hypot(x - cx, y - cy) / max;
        const k = 1 - strength * d * d;
        const i = (y * this.w + x) * 4;
        this.px[i] *= k; this.px[i + 1] *= k; this.px[i + 2] *= k;
      }
    }
  }

  /** A copy of this surface, for effects that need the untouched original. */
  clone() {
    const c = new Surface(this.w, this.h, 1);
    c.px.set(this.px);
    return c;
  }

  /** Screen-blend another surface over this one, optionally tinted. */
  screen(src, amount = 1, tint = [1, 1, 1]) {
    for (let i = 0; i < this.px.length; i += 4) {
      for (let k = 0; k < 3; k++) {
        const a = this.px[i + k];
        const b = src.px[i + k] * tint[k] * amount;
        this.px[i + k] = clamp01(1 - (1 - a) * (1 - clamp01(b)));
      }
    }
  }

  /**
   * Halation: the glow film gets where a bright highlight scatters back off the
   * base layer. It reads warm-red on colour stock, which is exactly why it is
   * the signature of a photograph shot on film rather than a sensor.
   */
  halation(threshold = 0.62, radius = 0.05, strength = 0.55, tint = [1, 0.34, 0.2]) {
    const glow = this.clone();
    // Keep only what is brighter than the threshold, rolled off softly.
    for (let i = 0; i < glow.px.length; i += 4) {
      const l = 0.299 * glow.px[i] + 0.587 * glow.px[i + 1] + 0.114 * glow.px[i + 2];
      const k = smooth(threshold, 1, l);
      glow.px[i] *= k;
      glow.px[i + 1] *= k;
      glow.px[i + 2] *= k;
    }
    glow.blur(this.w * radius);
    this.screen(glow, strength, tint);
  }

  /**
   * A chevron band.
   *
   * The dentelle course that runs around the top of the Great Enclosure at
   * Great Zimbabwe is a band of chevrons laid in stone. It is the most
   * recognisable piece of Zimbabwean architectural pattern there is, and it
   * makes a natural rule: it wants to run in a line, and it reads at any size.
   */
  chevron(x, y, w, h, color, alpha = 1, step) {
    const s = step ?? h;
    for (let i = 0; i * s < w + s; i++) {
      const x0 = x + i * s;
      // Each chevron is two strokes meeting at the apex.
      for (let t = 0; t < s / 2; t++) {
        const px = x0 + t;
        if (px < x || px >= x + w) continue;
        const up = h - (t / (s / 2)) * h;
        this.rect(px, y + up - h * 0.34, 1, h * 0.34, color, alpha);
        const px2 = x0 + s - t;
        if (px2 < x || px2 >= x + w) continue;
        this.rect(px2, y + up - h * 0.34, 1, h * 0.34, color, alpha);
      }
    }
  }

  /** Five-pointed star — the one on the flag, and the reference covers' mark. */
  star(cx, cy, radius, color, alpha = 1, rot = -Math.PI / 2) {
    // Rasterised by scanline: for each row, find where the polygon's edges
    // cross it and fill between the crossings.
    const pts = [];
    for (let i = 0; i < 10; i++) {
      const r = i % 2 === 0 ? radius : radius * 0.4;
      const a = (i / 10) * Math.PI * 2 + rot;
      pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
    }
    const y0 = Math.max(0, Math.floor(cy - radius));
    const y1 = Math.min(this.h, Math.ceil(cy + radius));
    for (let y = y0; y < y1; y++) {
      const xs = [];
      for (let i = 0; i < pts.length; i++) {
        const [ax, ay] = pts[i];
        const [bx, by] = pts[(i + 1) % pts.length];
        if (ay === by) continue;
        if (y + 0.5 >= Math.min(ay, by) && y + 0.5 < Math.max(ay, by)) {
          xs.push(ax + ((y + 0.5 - ay) / (by - ay)) * (bx - ax));
        }
      }
      xs.sort((a, b) => a - b);
      for (let i = 0; i + 1 < xs.length; i += 2) {
        this.rect(xs[i], y, xs[i + 1] - xs[i], 1, color, alpha);
      }
    }
  }

  /**
   * The flag band: green, gold, red, black stacked into one rule. The whole
   * palette on the page at once, in the width of a hairline.
   */
  flagBand(x, y, w, h, colors, alpha = 1) {
    const band = h / colors.length;
    for (const [i, c] of colors.entries()) {
      this.rect(x, y + i * band, w, Math.ceil(band), c, alpha);
    }
  }

  /**
   * A sun: solid disc with tapered rays radiating from it. Straight out of the
   * first reference, and the oldest graphic device there is.
   */
  sunDisc(cx, cy, radius, color, alpha = 1, rays = 0, rayLen = 0) {
    if (rays > 0) {
      for (let i = 0; i < rays; i++) {
        const a = (i / rays) * Math.PI * 2;
        const inner = radius * 1.12;
        const outer = inner + rayLen * (0.72 + 0.5 * this.rand());
        const mx = cx + Math.cos(a) * (inner + outer) / 2;
        const my = cy + Math.sin(a) * (inner + outer) / 2;
        this.quad(mx, my, outer - inner, radius * 0.11, a, color, alpha, 1.2);
      }
    }
    this.disc(cx, cy, radius, radius, 0, color, alpha, 1.5);
  }

  /** Set a line of small type. Returns the x the line ended at. */
  text(str, x, y, scale, color, opts = {}) {
    const { tracking = 1, alpha = 1 } = opts;
    let cx = x;
    for (const ch of String(str)) {
      const g = glyph(ch);
      if (g) {
        for (let row = 0; row < GLYPH_H; row++) {
          for (let col = 0; col < GLYPH_W; col++) {
            if (!(g[row] & (1 << (GLYPH_W - 1 - col)))) continue;
            this.rect(cx + col * scale, y + row * scale, scale, scale, color, alpha);
          }
        }
      }
      cx += (GLYPH_W + tracking) * scale;
    }
    return cx;
  }

  /** Width a string will occupy at `scale`, for right-aligning. */
  textWidth(str, scale, tracking = 1) {
    return String(str).length * (GLYPH_W + tracking) * scale - tracking * scale;
  }

  /**
   * The black rebate around a medium-format frame: the unexposed film border,
   * with edge printing, frame number and the notch marks off a 120 back.
   * Drawn *outside* the picture area, which must already be in place.
   */
  filmRebate(x, y, w, h, opts = {}) {
    const { pad = Math.round(w * 0.018), stock, frame, printed = false } = opts;
    const ink = [0.05, 0.045, 0.045];

    // The four bands.
    this.rect(x - pad, y - pad, w + pad * 2, pad, ink);
    this.rect(x - pad, y + h, w + pad * 2, pad, ink);
    this.rect(x - pad, y, pad, h, ink);
    this.rect(x + w, y, pad, h, ink);

    if (!printed) return;

    // Edge printing, only where the band is deep enough to carry it.
    const light = [0.86, 0.84, 0.8];
    const t = Math.max(1, Math.floor((pad * 0.62) / GLYPH_H));
    if (GLYPH_H * t > pad) return;
    this.text(`${stock}  ${frame}`, x + t * 2, y - pad + (pad - GLYPH_H * t) / 2, t, light, { alpha: 0.85 });
    const fw = this.textWidth(`120  ${frame}A`, t);
    this.text(`120  ${frame}A`, x + w - fw - t * 2, y + h + (pad - GLYPH_H * t) / 2, t, light, { alpha: 0.85 });
  }

  /**
   * Break a region into a coarse grid and keep only the cells that carry
   * light — the dithered, half-printed look off a blown-up newsprint scan.
   * Cells that fail the threshold are cleared to `ground`, so the flat colour
   * underneath reads through the picture.
   */
  mosaic(x, y, w, h, cell, ground, opts = {}) {
    const { keep = 0.62, hot = 0.16, jitter = 0.1, blank = [1, 1, 1] } = opts;
    const cols = Math.ceil(w / cell);
    const rows = Math.ceil(h / cell);
    const gap = Math.max(1, Math.round(cell * 0.14)); // grid lines between cells

    // Pass one: average each cell.
    const cells = [];
    for (let cy = 0; cy < rows; cy++) {
      for (let cx = 0; cx < cols; cx++) {
        const px = Math.round(x + cx * cell);
        const py = Math.round(y + cy * cell);
        const cw = Math.min(cell, x + w - px);
        const ch = Math.min(cell, y + h - py);
        if (cw <= 0 || ch <= 0) continue;
        let r = 0, g = 0, b = 0, n = 0;
        for (let yy = py; yy < py + ch; yy += 2) {
          for (let xx = px; xx < px + cw; xx += 2) {
            if (xx < 0 || yy < 0 || xx >= this.w || yy >= this.h) continue;
            const i = (yy * this.w + xx) * 4;
            r += this.px[i]; g += this.px[i + 1]; b += this.px[i + 2]; n++;
          }
        }
        if (!n) continue;
        cells.push({ px, py, cw, ch, lum: (0.299 * r + 0.587 * g + 0.114 * b) / n });
      }
    }

    // Pass two: thresholds taken from this image's own distribution, so the
    // proportion that survives is the same whatever the duotone is doing.
    const sorted = [...cells].map((c) => c.lum).sort((a, b) => a - b);
    const at = (q) => sorted[Math.min(sorted.length - 1, Math.floor(q * sorted.length))] ?? 0;
    const cut = at(1 - keep);
    const hotCut = at(1 - hot);

    for (const c of cells) {
      const lum = c.lum + (this.rand() - 0.5) * jitter;
      if (lum < cut) {
        this.rect(c.px, c.py, c.cw, c.ch, ground); // knocked back to flat colour
      } else if (lum > hotCut) {
        this.rect(c.px, c.py, c.cw - gap, c.ch - gap, blank); // blown highlight
      } else {
        this.rect(c.px + c.cw - gap, c.py, gap, c.ch, ground);
        this.rect(c.px, c.py + c.ch - gap, c.cw, gap, ground);
      }
    }
  }

  toPNG() {
    const out = Buffer.alloc(this.w * this.h * 4);
    for (let i = 0; i < this.px.length; i++) out[i] = Math.round(clamp01(this.px[i]) * 255);
    return encodePNG(this.w, this.h, out);
  }

  /**
   * Nearest-neighbour blit with an optional source rectangle, which is what
   * lets a 3:2 frame be cropped square for a 6×6 plate.
   */
  blit(src, dx, dy, dw, dh, crop) {
    const { sx0 = 0, sy0 = 0, sw = src.w, sh = src.h } = crop ?? {};
    for (let y = 0; y < dh; y++) {
      const sy = Math.min(src.h - 1, Math.floor(sy0 + (y / dh) * sh));
      for (let x = 0; x < dw; x++) {
        const sx = Math.min(src.w - 1, Math.floor(sx0 + (x / dw) * sw));
        const si = (sy * src.w + sx) * 4;
        const tx = dx + x;
        const ty = dy + y;
        if (tx < 0 || ty < 0 || tx >= this.w || ty >= this.h) continue;
        const ti = (ty * this.w + tx) * 4;
        this.px[ti] = src.px[si];
        this.px[ti + 1] = src.px[si + 1];
        this.px[ti + 2] = src.px[si + 2];
        this.px[ti + 3] = 1;
      }
    }
  }
}

