const PAGE_W = 900;
const PAGE_H = 1274; // ~1:1.414

/**
 * Art-directed grid templates, laid out on a 12 × 14 unit block.
 *
 * Each is `[x, y, w, h]` in units, so the aspect of every tile is fixed by the
 * layout rather than left to chance: a wide establishing frame, two or three
 * landscape frames, and exactly one upright. Which template a page gets is
 * seeded, so the pages differ but none of them can come out badly composed.
 */
const GRID_TEMPLATES = [
  // Wide opener, pair beneath, upright anchoring the foot.
  [[0, 0, 12, 5], [0, 5, 7, 4], [7, 5, 5, 4], [0, 9, 4, 5], [4, 9, 8, 5]],
  // Upright leads, wide frame closes.
  [[0, 0, 4, 6], [4, 0, 8, 6], [0, 6, 7, 4], [7, 6, 5, 4], [0, 10, 12, 4]],
  // Letterbox across the top, upright in the middle band.
  [[0, 0, 12, 4], [0, 4, 5, 6], [5, 4, 7, 6], [0, 10, 6, 4], [6, 10, 6, 4]],
];
const GRID_COLS = 12;
const GRID_ROWS = 14;

/**
 * Crop window that fills `aspect` from a source frame without squashing it,
 * nudged off-centre so a row of frames doesn't read as mechanically aligned.
 */
function cropTo(src, aspect, rand) {
  let sw = src.w;
  let sh = sw / aspect;
  if (sh > src.h) {
    sh = src.h;
    sw = sh * aspect;
  }
  // Pull in slightly so there is room to move the window around.
  sw *= 0.92;
  sh *= 0.92;
  return {
    sx0: (src.w - sw) * (0.2 + rand() * 0.6),
    sy0: (src.h - sh) * (0.2 + rand() * 0.6),
    sw,
    sh,
  };
}

/** Square-ish crop window into a 3:2 frame, for 6×6 plates. */
function squareCrop(frame) {
  const size = frame.h;
  return { sx0: (frame.w - size) / 2, sy0: 0, sw: size, sh: size };
}

/**
 * A printed page, in red, white and black.
 *
 * Five ways of putting work on paper, following the reference programme: an
 * opening statement page, a wide hero still under a credit block, a six-up
 * grid beside a standfirst, a single medium-format plate, and a proof sheet.
 *
 * `meta.mirror` composes a LEFT-hand page: the gutter moves to the right edge
 * and every element is placed from the other side. It has to be done in the
 * layout rather than by flipping pixels, because the shader already flips the
 * UVs of back faces — flipping the art as well would leave the gutter on the
 * spine but every line of type running backwards.
 */
function makePage(frame, variant, seed, tone, layout, meta) {
  const s = new Surface(PAGE_W, PAGE_H, seed + 7777);
  const ink = hex(PAPER.ink);
  const red = hex(PAPER.red);
  const stock = hex(PAPER.stock);
  const white = hex(PAPER.white);

  const grounds = { paper: stock, red, ink };
  const kind = layout.ground ?? "paper";
  const gold = hex(PAPER.gold);
  const green = hex(PAPER.green);
  const FLAG = [green, gold, red, ink];
  const ground = grounds[kind];
  const onDark = kind !== "paper";
  const type = onDark ? stock : ink;
  /** Red loses against red; on a red page the accent role falls to the stock. */
  const spot = kind === "red" ? stock : red;

  s.fill(ground[0], ground[1], ground[2], 1);
  s.grain(0.008); // just enough tooth; the page-wide CSS grain does the rest

  const mirror = !!meta.mirror;
  /** Map an x measured from the gutter side onto the page. */
  const place = (x, w) => (mirror ? PAGE_W - x - w : x);
  /** Draw a line of type, positioned from the gutter side. */
  const put = (str, x, y, scale, color, opts) =>
    s.text(str, place(x, s.textWidth(str, scale, opts?.tracking ?? 1)), y, scale, color, opts);
  /** A rule, positioned from the gutter side. */
  const rule = (x, y, w, h, color, alpha) => s.rect(place(x, w), y, w, h, color, alpha);

  const gutter = Math.round(PAGE_W * 0.1); // clearance for the rings
  const margin = Math.round(PAGE_W * 0.07);
  const colW = PAGE_W - gutter - margin;
  const t = 2; // small-type scale
  const lead = GLYPH_H * t + 7;

  /** The label block: a red bar, a role, a name. Set bold, set small. */
  const creditBlock = (x, y) => {
    rule(x, y, Math.round(colW * 0.16), 6, spot, 1);
    s.chevron(place(x, colW), y - Math.round(PAGE_H * 0.028), colW, Math.round(PAGE_H * 0.015), gold, 0.9, Math.round(PAGE_W * 0.036));
    put(meta.role, x, y + 18, t - 1, type, { alpha: 0.62, tracking: 2 });
    put(meta.name, x, y + 18 + GLYPH_H * (t - 1) + 10, t + 1, type, { alpha: 1, tracking: 1 });
  };

  /** Justified-looking standfirst, wrapped to the column. */
  const standfirst = (x, y, w, lines) => {
    let cy = y;
    for (const line of lines) {
      put(line, x, cy, t - 1, type, { alpha: 0.8 });
      cy += GLYPH_H * (t - 1) + 6;
    }
    return cy;
  };

  if (layout.kind === "title") {
    // The flag band runs off the top edge of the sheet.
    s.flagBand(place(gutter, colW), Math.round(PAGE_H * 0.045), colW, Math.round(PAGE_H * 0.012), FLAG);

    // Sun next, so everything else prints over it.
    // Small and high, clear of the section list — an emblem, not a subject.
    s.sunDisc(
      place(gutter + colW * 0.84, 0),
      Math.round(PAGE_H * 0.145),
      Math.round(PAGE_W * 0.062),
      gold,
      1,
      20,
      Math.round(PAGE_W * 0.042)
    );

    // Opening statement: flat red, heavy rules, the four sections listed.
    rule(gutter, Math.round(PAGE_H * 0.1), colW, 10, stock, 1);
    put(meta.name, gutter, Math.round(PAGE_H * 0.12), t + 2, stock, { tracking: 2 });
    put("SELECTED WORK", gutter, Math.round(PAGE_H * 0.16), t, stock, { alpha: 0.7, tracking: 3 });

    let y = Math.round(PAGE_H * 0.32);
    for (const [i, name] of meta.sections.entries()) {
      rule(gutter, y - 12, colW, 2, stock, 0.35);
      s.star(place(gutter - Math.round(PAGE_W * 0.026), 0), y + 6, Math.round(PAGE_W * 0.011), gold, 1);
      put(String(i + 1).padStart(2, "0"), gutter, y, t, stock, { alpha: 0.65 });
      put(name, gutter + Math.round(colW * 0.14), y - 4, t + 3, stock, { tracking: 1 });
      y += Math.round(PAGE_H * 0.09);
    }
    rule(gutter, y - 12, colW, 2, stock, 0.35);

    put("TURN THE PAGE", gutter, Math.round(PAGE_H * 0.83), t, stock, { alpha: 0.85, tracking: 3 });
    // A chevron course along the foot, the way it runs around a stone wall.
    s.chevron(place(gutter, colW), Math.round(PAGE_H * 0.88), colW, Math.round(PAGE_H * 0.02), gold, 1, Math.round(PAGE_W * 0.042));
  } else if (layout.kind === "hero") {
    // One wide still, credit block above it — the reference's left page.
    creditBlock(gutter, Math.round(PAGE_H * 0.1));
    const y = Math.round(PAGE_H * 0.3);
    const h = Math.round(PAGE_H * 0.42);
    s.blit(frame, place(gutter, colW), y, colW, h);
    s.filmRebate(place(gutter, colW), y, colW, h, { pad: Math.round(colW * 0.012) });
    rule(gutter, y + h + 14, colW, 2, type, 0.55);
    put(meta.caption, gutter, y + h + 24, t - 1, type, { alpha: 0.72 });
    // Folio, set in the spot colour.
    const fw = s.textWidth(meta.folio, t + 1) + 18;
    s.rect(place(gutter, fw), Math.round(PAGE_H * 0.88), fw, GLYPH_H * (t + 1) + 14, spot, 1);
    put(meta.folio, gutter + 9, Math.round(PAGE_H * 0.88) + 7, t + 1, kind === "red" ? red : white);
  } else if (layout.kind === "grid") {
    // Standfirst, then a six-up of stills — the reference's right page.
    const y0 = Math.round(PAGE_H * 0.1);
    rule(gutter, y0, Math.round(colW * 0.16), 6, spot, 1);
    const y1 = standfirst(gutter, y0 + 18, colW, meta.standfirst);

    const template = GRID_TEMPLATES[seed % GRID_TEMPLATES.length];
    const gap = Math.round(colW * 0.022);
    const top = y1 + Math.round(PAGE_H * 0.035);
    // Unit size is whichever of width or height runs out first.
    const unit = Math.min(colW / GRID_COLS, (PAGE_H * 0.88 - top) / GRID_ROWS);
    const blockW = unit * GRID_COLS;
    const originX = gutter + Math.round((colW - blockW) / 2);

    template.forEach(([gx, gy, gw, gh], k) => {
      const tw = Math.round(gw * unit) - gap;
      const th = Math.round(gh * unit) - gap;
      const x = place(Math.round(originX + gx * unit), tw);
      const y = Math.round(top + gy * unit);
      const src = variant(k);
      s.blit(src, x, y, tw, th, cropTo(src, tw / th, s.rand));
    });

    const gridBottom = Math.round(top + GRID_ROWS * unit);
    s.flagBand(place(gutter, colW), gridBottom + 10, colW, Math.round(PAGE_H * 0.01), FLAG);
    rule(gutter, gridBottom + Math.round(PAGE_H * 0.028), colW, 2, type, 0.55);
    put(meta.caption, gutter, gridBottom + Math.round(PAGE_H * 0.028) + 10, t - 1, type, { alpha: 0.72 });
  } else if (layout.kind === "plate") {
    // One frame, printed with its film border showing.
    const pad = Math.round(colW * 0.016);
    const size = Math.min(colW - pad * 2, Math.round(PAGE_H * 0.5));
    const x = gutter + pad + Math.round((colW - pad * 2 - size) / 2);
    const y = Math.round(PAGE_H * 0.26);
    creditBlock(gutter, Math.round(PAGE_H * 0.1));
    s.blit(frame, place(x, size), y, size, size, squareCrop(frame));
    s.filmRebate(place(x, size), y, size, size, { pad });
    rule(gutter, y + size + pad + 20, colW, 2, type, 0.55);
    put(meta.caption, gutter, y + size + pad + 30, t - 1, type, { alpha: 0.72 });
  } else if (layout.kind === "poster") {
    // One frame, screened coarse enough that the dots are the point, on flat
    // red with only a line of tracked-out credits under it.
    // Landscape band, set low, with flat colour breathing above it.
    const h = Math.round(colW / 1.5);
    const y = Math.round(PAGE_H * 0.34);
    const x = place(gutter, colW);
    s.blit(frame, x, y, colW, h, cropTo(frame, colW / h, s.rand));
    // Print to the full range before screening, then add a little bite.
    s.levels(x, y, colW, h, 0.03, 0.97);
    s.contrast(1.15, 0.5);
    s.halftone(x, y, colW, h, Math.max(5, Math.round(colW / 68)), ground, stock, 22);

    // Credits, spaced right out across the full measure.
    const y2 = y + h + Math.round(PAGE_H * 0.04);
    s.chevron(place(gutter, colW), y2 - Math.round(PAGE_H * 0.03), colW, Math.round(PAGE_H * 0.018), gold, 1, Math.round(PAGE_W * 0.04));
    rule(gutter, y2, colW, 4, stock, 1);
    put(meta.section, gutter, y2 + 18, t + 1, stock, { tracking: 5 });
    put(meta.credit, gutter, y2 + 18 + GLYPH_H * (t + 1) + 12, t - 1, stock, { alpha: 0.75, tracking: 4 });
    const fw = s.textWidth(meta.folio, t + 2);
    put(meta.folio, gutter + colW - fw, y2 + 14, t + 2, stock, { alpha: 0.9 });

    // Stamped block, the way a rating mark sits in the corner of a sleeve.
    const sw = Math.round(colW * 0.3);
    const sh = Math.round(PAGE_H * 0.062);
    const sx = place(gutter + colW - sw, sw);
    const sy = Math.round(PAGE_H * 0.86);
    s.rect(sx, sy, sw, sh, ink, 1);
    put(meta.name, gutter + colW - sw + 10, sy + 8, t - 1, stock, { tracking: 3 });
    s.rect(sx, sy + Math.round(sh * 0.4), sw, Math.round(sh * 0.34), stock, 1);
    put(meta.section, gutter + colW - sw + 10, sy + Math.round(sh * 0.46), t - 1, ink, { tracking: 2 });
    put("VOL 01", gutter + colW - sw + 10, sy + Math.round(sh * 0.8), t - 1, stock, { alpha: 0.8, tracking: 3 });
  } else {
    // Proof sheet: the same roll, six ways.
    const cols = 2;
    const rows = 3;
    const gap = Math.round(colW * 0.05);
    const top = Math.round(PAGE_H * 0.16);
    const availH = PAGE_H * 0.9 - top;
    const cellW = Math.min(
      (colW - gap * (cols - 1)) / cols,
      (availH - gap * (rows - 1)) / rows
    );
    const cellPad = Math.round(cellW * 0.055);
    const picW = Math.round(cellW - cellPad * 2);
    const left = gutter + Math.round((colW - (cellW * cols + gap * (cols - 1))) / 2);

    rule(gutter, Math.round(PAGE_H * 0.1), Math.round(colW * 0.16), 6, spot, 1);
    put(meta.caption, gutter, Math.round(PAGE_H * 0.115), t, type, { alpha: 0.9 });
    rule(gutter, Math.round(PAGE_H * 0.142), colW, 2, type, 0.5);

    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        const x = place(Math.round(left + c * (cellW + gap)) + cellPad, picW);
        const y = Math.round(top + r * (cellW + gap)) + cellPad;
        const src = variant(r * cols + c);
        const size = src.h * (0.62 + 0.3 * s.rand());
        s.blit(src, x, y, picW, picW, {
          sx0: (src.w - size) * s.rand(),
          sy0: (src.h - size) * s.rand(),
          sw: size,
          sh: size,
        });
        s.filmRebate(x, y, picW, picW, {
          pad: cellPad,
          stock: meta.stock,
          frame: String(r * cols + c + 1).padStart(2, "0"),
          printed: true, // a proof sheet without frame numbers is not a proof sheet
        });
        // Grease-pencil select mark, as on a real proof sheet.
        if (r * cols + c === meta.pick) {
          const b = Math.max(2, Math.round(cellPad * 0.42));
          s.rect(x - cellPad, y - cellPad, picW + cellPad * 2, b, spot);
          s.rect(x - cellPad, y + picW + cellPad - b, picW + cellPad * 2, b, spot);
          s.rect(x - cellPad, y - cellPad, b, picW + cellPad * 2, spot);
          s.rect(x + picW + cellPad - b, y - cellPad, b, picW + cellPad * 2, spot);
        }
      }
    }
  }

  // Register marks at the outer corners.
  const m = 26;
  for (const my of [m, PAGE_H - m - 2]) {
    s.rect(place(PAGE_W - m - 40, 40), my, 40, 2, type, 0.4);
    s.rect(place(PAGE_W - m - 2, 2), my - 18, 2, 40, type, 0.4);
  }

  // Running head down the gutter side.
  put(meta.running, Math.round(PAGE_W * 0.075), Math.round(PAGE_H * 0.955), 1, type, { alpha: 0.45 });

  // Wear shadow around each punch. The holes themselves are cut by the shared
  // alpha mask, so the art can stay a flat opaque JPEG.
  const holeCx = mirror ? PAGE_W - HOLE_X * PAGE_W : HOLE_X * PAGE_W;
  for (const ts of HOLE_TS) {
    s.blob(holeCx, PAGE_H * ts, HOLE_R * PAGE_W * 3.2, HOLE_R * PAGE_W * 3.2, 0, [0, 0, 0], 0.22, 1.6);
  }

  void lead;
  return s;
}

const HOLE_X = 0.045;
const HOLE_R = 0.021;
const HOLE_TS = [0.22, 0.5, 0.78];

/**
 * One small greyscale mask, shared by every page, that punches the ring holes.
 *
 * Keeping the holes out of the artwork means page art needs no alpha channel —
 * so it can be a JPEG, and so real photographs drop straight in without anyone
 * having to cut holes in them.
 */
function makeMask() {
  const w = 180;
  const h = Math.round((PAGE_H / PAGE_W) * w);
  const s = new Surface(w, h, 4242);
  s.fill(1, 1, 1, 1);
  for (const t of HOLE_TS) {
    s.disc(HOLE_X * w, h * t, HOLE_R * w, HOLE_R * w, 0, [0, 0, 0], 1, 1.2);
  }
  return s;
}

