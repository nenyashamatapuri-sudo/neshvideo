const BLACK = [0.015, 0.015, 0.02];
const WHITE = [0.97, 0.96, 0.93];

/**
 * Backlit subject, framed waist-up so the body is cropped by the frame the way
 * a real portrait is. Full-length figures read as clipart; tight crops don't.
 */
function sceneFigure(s, r) {
  const { w, h } = s;
  s.ramp(70 + r() * 40, [0.03, 0.03, 0.04], [0.3, 0.29, 0.3]);

  // Backlight blooming behind the subject's head.
  const lx = w * (0.34 + r() * 0.32);
  const ly = h * (0.2 + r() * 0.16);
  s.blob(lx, ly, w * 0.42, h * 0.5, 0, WHITE, 0.85, 1.9);
  s.disc(lx, ly, w * 0.03, w * 0.03, 0, [1, 1, 1], 0.9, 7);

  // Crowd depth: smaller figures, thrown well out of focus.
  for (let i = 0; i < 2 + Math.floor(r() * 2); i++) {
    s.figure(w * (0.05 + r() * 0.9), h * (1.15 + r() * 0.25), h * (0.75 + r() * 0.3), BLACK, 0.42, r());
  }
  s.blur(w * 0.022);

  // Hero subject: tall enough that the frame crops it at the waist.
  const cx = w * (0.28 + r() * 0.44);
  const u = h * (1.55 + r() * 0.45);
  s.figure(cx, h * (1.6 + r() * 0.35), u, BLACK, 0.96, r());

  // Rim light down one shoulder and arm.
  s.blob(cx + u * 0.115, h * 0.42, w * 0.022, h * 0.34, 0.05, WHITE, 0.4, 2.4);
  s.blob(cx - u * 0.1, h * 0.36, w * 0.016, h * 0.22, -0.04, WHITE, 0.22, 2.4);

  // Atmosphere, then a touch of defocus so no edge is vector-hard.
  s.blob(w * 0.5, h * 0.72, w * 0.75, h * 0.42, 0, [0.6, 0.6, 0.62], 0.18, 1.4);
  s.blur(w * 0.005);
}

/**
 * Hard geometry and light shafts — commercial / interior. Deliberately busy:
 * these frames get cropped hard on the proof sheets, so every corner needs
 * something in it.
 */
function sceneArch(s, r) {
  const { w, h } = s;
  s.ramp(150 + r() * 60, [0.04, 0.04, 0.05], [0.6, 0.59, 0.57]);

  // Wall planes, back to front.
  for (let i = 0; i < 6 + Math.floor(r() * 4); i++) {
    const dark = r() > 0.5;
    s.quad(w * r(), h * r(), w * (0.08 + r() * 0.4), h * (0.15 + r() * 0.9),
      (r() - 0.5) * 0.25, dark ? BLACK : WHITE, 0.16 + r() * 0.38);
  }

  // A run of windows: the strongest cue that this is a building.
  const wy = h * (0.18 + r() * 0.3);
  const wh = h * (0.16 + r() * 0.2);
  const cols = 3 + Math.floor(r() * 4);
  const pitch = w / (cols + 0.6);
  const skew = (r() - 0.5) * 0.14;
  for (let i = 0; i < cols; i++) {
    const wx = pitch * (i + 0.7);
    s.quad(wx, wy + (wx - w / 2) * skew, pitch * 0.44, wh, skew, WHITE, 0.55 + r() * 0.35);
    s.quad(wx, wy + wh * 0.55 + (wx - w / 2) * skew, pitch * 0.44, wh * 0.06, skew, BLACK, 0.5);
  }

  // Columns and a floor edge to anchor the perspective.
  for (let i = 0; i < 2 + Math.floor(r() * 3); i++) {
    s.quad(w * r(), h * 0.55, w * (0.02 + r() * 0.035), h * 1.3, skew * 1.4, BLACK, 0.45 + r() * 0.4);
  }
  // Floor edge: a wide soft-edged bar rather than a hard horizon.
  const fy = h * (0.72 + r() * 0.18);
  s.quad(w / 2, fy + h * 0.3, w * 2, h * 0.6, (r() - 0.5) * 0.09, BLACK, 0.55, h * 0.05);

  // Shafts of light across the floor.
  const n = 2 + Math.floor(r() * 3);
  for (let i = 0; i < n; i++) {
    s.quad(w * (0.12 + (i / n) * 0.9), h * 0.5, w * (0.015 + r() * 0.04), h * 1.6,
      skew - 0.2, WHITE, 0.32 + r() * 0.3, 26);
  }

  // Figures for scale — one near, one far.
  s.figure(w * (0.1 + r() * 0.8), fy + h * (0.02 + r() * 0.1), h * (0.3 + r() * 0.24), BLACK, 0.9, r());
  if (r() > 0.4) {
    s.figure(w * r(), fy - h * 0.01, h * (0.14 + r() * 0.1), BLACK, 0.7, r());
  }

  s.blob(w * r(), h * 0.2, w * 0.5, h * 0.5, 0, WHITE, 0.18, 2);
  s.blur(w * 0.003);
}

/** Horizon, sun, atmospheric layers — the aerial / landscape plate. */
function sceneLand(s, r) {
  const { w, h } = s;
  const hz = h * (0.42 + r() * 0.3);
  s.ramp(90, [0.06, 0.07, 0.09], [0.72, 0.74, 0.76]);
  // Sky glow + sun.
  const sx = w * (0.2 + r() * 0.6);
  s.blob(sx, hz - h * 0.08, w * 0.55, h * 0.5, 0, WHITE, 0.75, 2.2);
  s.disc(sx, hz - h * 0.05, w * 0.022, w * 0.022, 0, [1, 1, 1], 0.95, 4);
  // Receding ridgelines, lighter as they go back.
  const ridges = 3 + Math.floor(r() * 3);
  for (let i = ridges; i >= 1; i--) {
    const t = i / ridges;
    const y = hz + (1 - t) * h * 0.3;
    const tone = lerp(0.45, 0.02, 1 - t);
    for (let k = 0; k < 4; k++) {
      s.disc(w * (r() * 1.2 - 0.1), y + h * 0.16, w * (0.18 + r() * 0.3), h * (0.08 + r() * 0.16), 0, [tone, tone, tone * 1.05], 0.9, 3);
    }
  }
  // Ground plane, hazed back so it doesn't read as a solid bar.
  s.quad(w / 2, h * 1.06, w * 2, h * 0.5, (r() - 0.5) * 0.06, BLACK, 0.7, h * 0.16);
  s.blob(w * (0.2 + r() * 0.6), h * 0.94, w * 0.6, h * 0.22, 0, WHITE, 0.13, 1.5);
  // Haze band on the horizon.
  s.blob(w / 2, hz, w * 1.2, h * 0.07, 0, WHITE, 0.5, 1.2);
}

/** Close-focus object with bokeh behind — product / detail. */
function sceneDetail(s, r) {
  const { w, h } = s;
  s.ramp(30 + r() * 120, [0.04, 0.04, 0.05], [0.4, 0.39, 0.4]);
  // Bokeh field.
  for (let i = 0; i < 14 + Math.floor(r() * 14); i++) {
    const rad = w * (0.015 + r() * 0.075);
    s.disc(w * r(), h * r(), rad, rad, 0, WHITE, 0.1 + r() * 0.3, rad * 0.5);
  }
  s.blur(w * 0.012);
  // Foreground object: stacked crisp blocks catching an edge light.
  const cx = w * (0.3 + r() * 0.4);
  const cy = h * (0.45 + r() * 0.25);
  const rot = (r() - 0.5) * 0.8;
  const ow = w * (0.16 + r() * 0.2);
  const oh = h * (0.3 + r() * 0.35);
  s.quad(cx, cy, ow, oh, rot, BLACK, 0.94);
  // Specular running down the lit edge, and a catch along the top.
  s.quad(cx - Math.cos(rot) * ow * 0.47, cy - Math.sin(rot) * ow * 0.47, w * 0.008, oh * 0.94, rot, WHITE, 0.6);
  s.quad(cx + Math.sin(rot) * oh * 0.47, cy - Math.cos(rot) * oh * 0.47, ow * 0.92, h * 0.006, rot, WHITE, 0.3);
  // Table shadow.
  s.blob(cx + w * 0.1, cy + h * 0.3, w * 0.3, h * 0.06, 0.1, BLACK, 0.6, 1.6);
}

const SCENES = { figure: sceneFigure, arch: sceneArch, land: sceneLand, detail: sceneDetail };

/**
 * One frame grab.
 *
 * Clean and sharp: no grain, no dust, no scratches, no light leaks. The only
 * thing kept from the emulsion pass is a whisper of halation, because that is
 * light behaving like light rather than a defect, and without it a rendered
 * frame reads as CGI.
 */
function makeFrame(w, h, seed, tone, scene) {
  const s = new Surface(w, h, seed);
  const r = s.rand;
  s.fill(0.08, 0.08, 0.09, 1);
  (SCENES[scene] ?? sceneFigure)(s, r);

  s.halation(0.72, 0.03, 0.2);

  s.grade(hex(tone.shadow), hex(tone.mid), hex(tone.highlight), tone.mix ?? 0.85);
  s.contrast(tone.contrast ?? 1.18);

  // One saturated mass, so the frame has a place for the eye to land.
  if (r() > 0.45) {
    s.prop(
      w * (0.15 + r() * 0.7),
      h * (0.3 + r() * 0.5),
      w * (0.03 + r() * 0.09),
      h * (0.04 + r() * 0.16),
      (r() - 0.5) * 0.5,
      hex(tone.prop),
      0.62 + r() * 0.3,
      r() > 0.65
    );
  }

  // Just enough falloff to seat the picture; not a lens defect.
  s.vignette(0.16);
  return s;
}

