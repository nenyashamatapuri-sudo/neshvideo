/** Write `surface` as JPEG via sips where available, PNG otherwise. */
function writeImage(dir, id, surface, quality = 82) {
  const png = path.join(dir, `${id}.png`);
  fs.writeFileSync(png, surface.toPNG());
  if (!jpeg) return;
  execFileSync("sips", ["-s", "format", "jpeg", "-s", "formatOptions", String(quality), png,
    "--out", path.join(dir, `${id}.jpg`)], { stdio: "ignore" });
  fs.unlinkSync(png);
}

