const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();

function crc32(buf) {
  let c = -1;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

const BPP = 4; // RGBA, 8 bits each

function paeth(a, b, c) {
  const p = a + b - c;
  const pa = Math.abs(p - a);
  const pb = Math.abs(p - b);
  const pc = Math.abs(p - c);
  return pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
}

/**
 * Filter one scanline five ways and keep the cheapest.
 *
 * PNG's filters are the whole reason it compresses photographs at all: on
 * smooth gradients an unfiltered line is nearly incompressible, while Paeth or
 * Up leaves deflate a run of near-zero bytes. Picking per line by minimum sum
 * of absolute differences is the heuristic the spec itself recommends.
 */
function filterScanline(line, prev, out, outOffset) {
  const n = line.length;
  let best = -1;
  let bestScore = Infinity;
  const cand = Buffer.alloc(n);

  for (let type = 0; type < 5; type++) {
    let score = 0;
    for (let i = 0; i < n; i++) {
      const a = i >= BPP ? line[i - BPP] : 0;
      const b = prev[i];
      const c = i >= BPP ? prev[i - BPP] : 0;
      let v;
      switch (type) {
        case 0: v = line[i]; break;
        case 1: v = line[i] - a; break;
        case 2: v = line[i] - b; break;
        case 3: v = line[i] - ((a + b) >> 1); break;
        default: v = line[i] - paeth(a, b, c);
      }
      v &= 0xff;
      cand[i] = v;
      score += v < 128 ? v : 256 - v; // treat as signed magnitude
    }
    if (score < bestScore) {
      bestScore = score;
      best = type;
      cand.copy(out, outOffset + 1);
    }
  }
  out[outOffset] = best;
}

function encodePNG(w, h, rgba) {
  const stride = w * BPP;
  const raw = Buffer.alloc((stride + 1) * h);
  let prev = Buffer.alloc(stride);

  for (let y = 0; y < h; y++) {
    const line = rgba.subarray(y * stride, y * stride + stride);
    filterScanline(line, prev, raw, y * (stride + 1));
    prev = line;
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // truecolour + alpha
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

