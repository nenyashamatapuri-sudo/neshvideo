/* Punctuation the copy uses but the face has no room for. Curly quotes and the
   long dashes fold onto their typewriter equivalents rather than vanishing. */
const FOLD = {
  "\u2019": "'", "\u2018": "'", "\u201c": '"', "\u201d": '"',
  "\u2014": "-", "\u2013": "-", "\u00b7": ".", "\u2026": "...",
};

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const fold = (ch) => FOLD[ch] ?? ch;
export const glyph = (ch) => {
  const c = fold(ch);
  return G[c] ?? G[c?.toUpperCase?.()] ?? null;
};
